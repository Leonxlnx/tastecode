export type TypographyCandidates = Record<keyof typeof DESIGN_FONT_POOLS, string[]>

export function selectTypographyCandidates(
  chooseIndex: (length: number) => number = randomInt,
): TypographyCandidates {
  return Object.fromEntries(
    Object.entries(DESIGN_FONT_POOLS).map(([role, families]) => {
      const remaining: string[] = [...families]
      const selected: string[] = []
      while (remaining.length) selected.push(remaining.splice(chooseIndex(remaining.length), 1)[0]!)
      return [role, selected]
    }),
  ) as TypographyCandidates
}

export function typographyGuidance(candidates: TypographyCandidates): string {
  return `TYPOGRAPHY DRAW — generated by node:crypto.randomInt and persisted for this run:
${JSON.stringify(candidates)}
First inspect the reference's letter shapes, width, contrast, case, weight, line breaks and hierarchy. Preserve any explicit or verified existing brand typeface. Otherwise choose the matching category (sans, serif, display or mono), then use its FIRST drawn family; do not pick a familiar font further down the list. Use the first sans family for body text when the reference pairs display type with a readable sans. The full permutation records the ten eligible choices; it is not a menu to reroll by taste. If acquisition fails, try the official repository and Google Fonts CSS for the SAME selected family before reporting the concrete source error.
Official specimens: https://fonts.google.com/specimen/ followed by the family with spaces replaced by +. Font files, weights and OFL notices: https://github.com/google/fonts/tree/main/ofl/ followed by the lowercase family without spaces. Assets must obtain a real usable font file and its license; Build must load it, wait for document.fonts.ready, and verify a matching loaded FontFace in document.fonts plus document.fonts.check with the actual family and weight. Merely declaring a family above Arial is not proof that it loaded. Match reference scale, width, tracking and line breaks instead of shrinking the composition to fit a fallback. Do not substitute Arial, Inter, Geist or system-ui as the designed face unless the user or existing brand explicitly requires it.`
}

export function validateTypographySelection(
  brief: DesignBrief,
  brand: BrandSystem,
  candidates: TypographyCandidates,
): void {
  if (brand.foundation.strategy !== 'create') return
  const explicit =
    `${brief.originalRequest} ${JSON.stringify(brief.brandInputs)} ${JSON.stringify(brief.explicitAnswers)}`.toLowerCase()
  const drawn = new Set(Object.values(candidates).map((families) => families[0]))
  for (const { family } of brand.typefaces) {
    if (drawn.has(family) || explicit.includes(family.toLowerCase())) continue
    throw new Error(
      `Use a persisted first-draw typeface for ${family}, or record the explicit existing-brand requirement. Do not replace the random draw with a habitual font.`,
    )
  }
}
