/** The scripted Codex's delta sizes: 1 to `max` characters from a fixed sequence. */
export function streamedChunks(text: string, max = 12): string[] {
  const chunks: string[] = []
  let seed = 7
  for (let index = 0; index < text.length;) {
    seed = (seed * 1103515245 + 12345) & 0x7fffffff
    const size = 1 + (seed % max)
    chunks.push(text.slice(index, index + size))
    index += size
  }
  return chunks
}
