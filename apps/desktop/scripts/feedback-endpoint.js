/**
 * The feedback inbox endpoint a packaged build ships with.
 *
 * The key is a Trecko public submit key. It is never committed: release
 * builds take it from the environment (a GitHub Actions secret in CI) or from
 * the maintainer's `~/.tastecode/trecko-feedback.env`, and this script writes
 * it to `dist/feedback/feedback.env`, which electron-builder copies into the
 * app's resources. Desktop main passes only that file's path to the server,
 * so the key never sits in an environment that agent CLIs and terminals
 * inherit. Builds without a key ship a file without one, and the app hides
 * feedback.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'

export const FEEDBACK_URL_ENV = 'TASTECODE_FEEDBACK_URL'
export const FEEDBACK_KEY_ENV = 'TASTECODE_FEEDBACK_KEY'
const KEY_PATTERN = /^fb_[A-Za-z0-9_]{8,96}$/

/** Same rules as the server: https only (loopback http for local fakes), a feedback-shaped key. */
export function validFeedbackEndpoint(raw) {
  const url = raw?.url?.trim()
  const key = raw?.key?.trim()
  if (!url || !key || !KEY_PATTERN.test(key)) return undefined
  let parsed
  try {
    parsed = new URL(url)
  } catch {
    return undefined
  }
  const loopback = parsed.hostname === '127.0.0.1' || parsed.hostname === '[::1]'
  if (parsed.protocol !== 'https:' && !(parsed.protocol === 'http:' && loopback)) return undefined
  if (parsed.username || parsed.password) return undefined
  return { url: parsed.toString(), key }
}

/** `KEY=VALUE` lines; `#` comments, `export` and surrounding quotes are allowed. */
export function parseFeedbackEnv(text) {
  const values = {}
  for (const line of String(text ?? '').split(/\r?\n/)) {
    const match = /^\s*(?:export\s+)?([A-Z_]+)\s*=\s*(.*?)\s*$/.exec(line)
    if (!match) continue
    const quoted = /^(["'])(.*)\1$/.exec(match[2])
    const value = quoted ? quoted[2] : match[2].replace(/\s+#.*$/, '')
    if (match[1] === FEEDBACK_URL_ENV) values.url = value
    if (match[1] === FEEDBACK_KEY_ENV) values.key = value
  }
  return values
}

function readText(file) {
  try {
    return readFileSync(file, 'utf8')
  } catch {
    return undefined
  }
}

/**
 * Explicit environment first, so CI and staging builds can choose an inbox.
 * A set but unusable environment value fails the build: someone asked for
 * feedback and would otherwise ship a build without it.
 */
export function resolveFeedbackEndpoint({
  env = process.env,
  home = os.homedir(),
  read = readText,
} = {}) {
  if (env[FEEDBACK_URL_ENV] || env[FEEDBACK_KEY_ENV]) {
    const endpoint = validFeedbackEndpoint({
      url: env[FEEDBACK_URL_ENV],
      key: env[FEEDBACK_KEY_ENV],
    })
    if (!endpoint)
      throw new Error(
        `${FEEDBACK_URL_ENV} and ${FEEDBACK_KEY_ENV} must name an https endpoint and a feedback key`,
      )
    return { endpoint, source: 'environment' }
  }
  const directory = env['HARNESS_CONFIG_DIR'] || path.join(home, '.tastecode')
  const text = read(path.join(directory, 'trecko-feedback.env'))
  if (text === undefined) return { source: 'none' }
  const endpoint = validFeedbackEndpoint(parseFeedbackEnv(text))
  return endpoint ? { endpoint, source: 'config file' } : { source: 'invalid config file' }
}

/** The generated resource. It never contains anything but the two feedback values. */
export function feedbackEnvFile(endpoint) {
  const header = '# Generated by apps/desktop/scripts/build-main.js. Never commit this file.\n'
  if (!endpoint) return `${header}# No feedback endpoint in this build.\n`
  return `${header}${FEEDBACK_URL_ENV}=${endpoint.url}\n${FEEDBACK_KEY_ENV}=${endpoint.key}\n`
}

/** Writes the resource and returns a log line that names only the host. */
export function writeFeedbackResource(outdir, options) {
  const { endpoint, source } = resolveFeedbackEndpoint(options)
  const directory = path.join(outdir, 'feedback')
  mkdirSync(directory, { recursive: true })
  writeFileSync(path.join(directory, 'feedback.env'), feedbackEnvFile(endpoint), { mode: 0o600 })
  return endpoint
    ? `feedback endpoint: ${new URL(endpoint.url).host} (from ${source})`
    : `feedback endpoint: none (${source})`
}
